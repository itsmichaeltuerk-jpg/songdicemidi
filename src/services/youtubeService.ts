/**
 * Extracts a YouTube Video ID from various URL patterns
 */
export function extractYouTubeVideoId(input: string): string | null {
  if (!input) return null;
  const trimmed = input.trim();

  // If already a clean 11-char ID
  if (/^[a-zA-Z0-9_-]{11}$/.test(trimmed)) {
    return trimmed;
  }

  // Regex patterns for YouTube and YouTube Music URLs
  const patterns = [
    /(?:https?:\/\/)?(?:www\.)?youtube\.com\/watch\?v=([a-zA-Z0-9_-]{11})/i,
    /(?:https?:\/\/)?(?:music\.)?youtube\.com\/watch\?v=([a-zA-Z0-9_-]{11})/i,
    /(?:https?:\/\/)?youtu\.be\/([a-zA-Z0-9_-]{11})/i,
    /(?:https?:\/\/)?(?:www\.)?youtube\.com\/embed\/([a-zA-Z0-9_-]{11})/i,
    /(?:https?:\/\/)?(?:www\.)?youtube\.com\/shorts\/([a-zA-Z0-9_-]{11})/i,
  ];

  for (const pattern of patterns) {
    const match = trimmed.match(pattern);
    if (match && match[1]) {
      return match[1];
    }
  }

  return null;
}

/**
 * Search the catalog and find matches for any query or URL
 */
export function searchYouTubeCatalog(query: string): YouTubeTrackItem[] {
  if (!query || !query.trim()) {
    return POPULAR_YOUTUBE_TRACKS.slice(0, 12);
  }

  const clean = query.trim().toLowerCase();
  const directId = extractYouTubeVideoId(query);

  if (directId) {
    const existing = POPULAR_YOUTUBE_TRACKS.find((t) => t.id === directId);
    if (existing) return [existing];

    // Build custom YouTube item for direct URL
    return [
      {
        id: directId,
        title: 'YouTube Track (' + directId + ')',
        artist: 'YouTube Music Source',
        thumbnailUrl: `https://img.youtube.com/vi/${directId}/hqdefault.jpg`,
        estimatedKey: 'A minor',
        estimatedBpm: 104,
        genre: 'Modern Pop / Custom YouTube Audio',
        duration: '3:30',
        youtubeUrl: `https://www.youtube.com/watch?v=${directId}`,
        chordsSummary: 'Auto-detected by Gemini AI',
        description: 'Arranging multi-track MIDI directly from provided YouTube video audio and harmony.',
      },
    ];
  }

  // Search by title, artist, genre, or description
  const filtered = POPULAR_YOUTUBE_TRACKS.filter((track) => {
    return (
      track.title.toLowerCase().includes(clean) ||
      track.artist.toLowerCase().includes(clean) ||
      track.genre?.toLowerCase().includes(clean) ||
      track.chordsSummary?.toLowerCase().includes(clean)
    );
  });

  if (filtered.length > 0) {
    return filtered;
  }

  // If no exact match in catalog, generate an on-the-fly candidate for Gemini to arrange
  const words = clean.split(/\s*-\s*|\s+by\s+|\s+/);
  const guessedTitle = query.length > 30 ? query.substring(0, 30) + '...' : query;

  return [
    {
      id: 'custom_' + Math.abs(hashCode(clean)).toString(36),
      title: guessedTitle.charAt(0).toUpperCase() + guessedTitle.slice(1),
      artist: words.length > 2 ? words[words.length - 1] : 'YouTube Artist',
      thumbnailUrl: 'https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=400&auto=format&fit=crop&q=80',
      estimatedKey: 'C major',
      estimatedBpm: 108,
      genre: 'Commercial Pop / YouTube Music',
      duration: '3:20',
      youtubeUrl: `https://www.youtube.com/results?search_query=${encodeURIComponent(query)}`,
      chordsSummary: 'Dynamic Gemini Analysis & Voicing',
      description: `Gemini AI will look up authentic chords, groove, and key for "${query}" and generate a full multi-track DAW MIDI arrangement.`,
    },
    ...POPULAR_YOUTUBE_TRACKS.slice(0, 6),
  ];
}

function hashCode(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const chr = str.charCodeAt(i);
    hash = (hash << 5) - hash + chr;
    hash |= 0;
  }
  return hash;
}
